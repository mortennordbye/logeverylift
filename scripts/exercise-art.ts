/**
 * Local pipeline for exercise illustrations (see .claude/skills/exercise-art).
 *
 *   pnpm art check [slug...]  validate specs and render .art-preview/<slug>.png
 *                             (--zoom: 2x preview, --joints: print where each joint ends up)
 *   pnpm art index            regenerate src/lib/exercise-art/specs/index.ts
 *   pnpm art todo             strength exercises from the seed that have no spec yet
 *   pnpm art map              render the muscle map to .art-preview/muscle-map.png
 */

import { chromium } from "@playwright/test";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { checkSpec } from "../src/lib/exercise-art/check";
import { artSpecSchema, resolvePoses, slugify } from "../src/lib/exercise-art/schema";
import { MAP_FIGURES, MAP_VIEWBOX } from "../src/lib/exercise-art/muscle-map";
import { MUSCLE_FILL, VIEWBOX, renderSvg } from "../src/lib/exercise-art/scene";
import { VIEWS, type Muscle } from "../src/lib/exercise-art/skeleton";

const ROOT = path.resolve(__dirname, "..");
const SPEC_DIR = path.join(ROOT, "src/lib/exercise-art/specs");
const PREVIEW_DIR = path.join(ROOT, ".art-preview");

const slugs = () => readdirSync(SPEC_DIR).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
const readSpec = (slug: string): unknown => JSON.parse(readFileSync(path.join(SPEC_DIR, `${slug}.json`), "utf8"));

// Tokens from src/app/globals.css and the blue accent in theme-provider.tsx.
const THEMES = {
  dark: "--card: oklch(0.205 0 0); --foreground: oklch(0.985 0 0); --muted-foreground: oklch(0.708 0 0); --primary: oklch(0.70 0.19 264.36);",
  light: "--card: oklch(1 0 0); --foreground: oklch(0.145 0 0); --muted-foreground: oklch(0.556 0 0); --primary: oklch(0.55 0.22 264.36);",
};
const MOMENTS = [0, 0.5, 1];

function previewHtml(slug: string, raw: unknown, zoom: number): string {
  const spec = artSpecSchema.parse(raw);
  const row = (theme: keyof typeof THEMES) =>
    `<div class="row" style="${THEMES[theme]}"><span class="theme">${theme}</span>` +
    VIEWS.flatMap((v) =>
      MOMENTS.map((t) => `<figure><svg viewBox="${VIEWBOX}">${renderSvg(spec, v, t, `${theme}-${v}-${t * 10}`)}</svg><figcaption>${v === "front" ? spec.camera : v} · t=${t}</figcaption></figure>`),
    ).join("") +
    `</div>`;
  return `<!doctype html><html><head><style>
    body { margin: 0; background: #000; font: 12px system-ui; }
    h1 { color: #ccc; font-size: 14px; margin: 8px 12px; }
    .row { display: flex; gap: 8px; padding: 8px; background: var(--card); }
    figure { margin: 0; text-align: center; color: var(--muted-foreground); }
    .theme { writing-mode: vertical-rl; color: var(--muted-foreground); }
    svg { width: ${200 * zoom}px; height: ${240 * zoom}px; display: block; }
  </style></head><body><h1>${spec.name} (${slug})</h1>${row("dark")}${row("light")}</body></html>`;
}

async function check(args: string[]) {
  const zoom = args.includes("--zoom") ? 2 : 1;
  const showJoints = args.includes("--joints");
  const only = args.filter((a) => !a.startsWith("--"));
  const targets = only.length ? only : slugs();
  let failed = false;
  mkdirSync(PREVIEW_DIR, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280 * zoom, height: 600 * zoom } });
  for (const slug of targets) {
    const raw = readSpec(slug);
    const problems = checkSpec(raw);
    const name = (raw as { name?: string }).name ?? "";
    if (name && slugify(name) !== slug) problems.push(`file name should be ${slugify(name)}.json for "${name}"`);
    if (problems.length) {
      failed = true;
      console.log(`✗ ${slug}\n${problems.map((p) => `  - ${p}`).join("\n")}`);
      continue;
    }
    if (showJoints) {
      // Where each joint really ends up once bone lengths are applied.
      resolvePoses(artSpecSchema.parse(raw)).forEach((pose, i) => {
        console.log(`  keyframe ${i}:`);
        for (const [j, p] of Object.entries(pose)) console.log(`    ${j.padEnd(10)} [${p.map((c) => c.toFixed(1)).join(", ")}]`);
      });
    }
    await page.setContent(previewHtml(slug, raw, zoom));
    const out = path.join(PREVIEW_DIR, `${slug}.png`);
    await page.screenshot({ path: out, fullPage: true });
    console.log(`✓ ${slug} → ${path.relative(ROOT, out)}`);
  }
  await browser.close();
  if (failed) process.exit(1);
}

function index() {
  const list = slugs();
  const lines = list.map((s) => `  ${JSON.stringify(s)}: () => import("./${s}.json").then((m) => m.default),`);
  writeFileSync(
    path.join(SPEC_DIR, "index.ts"),
    `// Generated by \`pnpm art index\`. Do not edit by hand.\n\nexport const SPEC_LOADERS: Record<string, () => Promise<unknown>> = {\n${lines.join("\n")}\n};\n`,
  );
  console.log(`index: ${list.length} specs`);
}

function todo() {
  const seed = readFileSync(path.join(ROOT, "scripts/seed.ts"), "utf8");
  const done = new Set(slugs());
  const names = [...seed.matchAll(/name: "([^"]+)",\s*category: "strength"/g)].map((m) => m[1]);
  const missing = names.filter((n) => !done.has(slugify(n)));
  console.log(missing.join("\n"));
  console.error(`${missing.length} of ${names.length} strength exercises have no illustration`);
}

/** The muscle map with a few highlight sets, in both themes. */
async function map() {
  const sets: [string, Partial<Record<Muscle, "primary" | "secondary">>][] = [
    ["nothing", {}],
    ["curl", { biceps: "primary", forearms: "secondary" }],
    ["bench", { chest: "primary", shoulders: "secondary", triceps: "secondary" }],
    ["deadlift", { hamstrings: "primary", glutes: "secondary", lower_back: "secondary", back: "secondary" }],
    ["squat", { quads: "primary", glutes: "secondary", calves: "secondary", abs: "secondary" }],
  ];
  const svg = (roles: Partial<Record<Muscle, "primary" | "secondary">>) =>
    `<svg viewBox="${MAP_VIEWBOX}">` +
    MAP_FIGURES.map((fig) =>
      `<g transform="translate(${fig.x} 0)">` +
      fig.shapes.map((s) => `<path d="${s.d}" style="fill:${s.muscle === null ? MUSCLE_FILL.body : MUSCLE_FILL[roles[s.muscle] ?? "none"]}"/>`).join("") +
      fig.lines.map((d) => `<path d="${d}" style="fill:none;stroke:${MUSCLE_FILL.line};stroke-width:1.2"/>`).join("") +
      `</g>`,
    ).join("") +
    `</svg>`;
  const row = (theme: keyof typeof THEMES) =>
    `<div class="row" style="${THEMES[theme]}">${sets.map(([label, roles]) => `<figure>${svg(roles)}<figcaption>${label}</figcaption></figure>`).join("")}</div>`;
  mkdirSync(PREVIEW_DIR, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 3000, height: 1200 } });
  await page.setContent(`<!doctype html><html><head><style>
    body { margin: 0; background: #000; font: 12px system-ui; }
    .row { display: flex; gap: 8px; padding: 8px; background: var(--card); }
    figure { margin: 0; text-align: center; color: var(--muted-foreground); }
    svg { width: 580px; height: 552px; display: block; }
  </style></head><body>${row("dark")}${row("light")}</body></html>`);
  const out = path.join(PREVIEW_DIR, "muscle-map.png");
  await page.screenshot({ path: out, fullPage: true });
  await browser.close();
  console.log(`✓ muscle map → ${path.relative(ROOT, out)}`);
}

const [cmd, ...rest] = process.argv.slice(2);
if (cmd === "check") void check(rest);
else if (cmd === "index") index();
else if (cmd === "todo") todo();
else if (cmd === "map") void map();
else {
  console.error("usage: pnpm art check [slug...] | index | todo | map");
  process.exit(1);
}
